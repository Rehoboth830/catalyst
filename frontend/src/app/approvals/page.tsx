"use client";

import { useEffect, useState } from "react";

type PendingAction = {
  action_id: string;
  action_type: string;
  cluster_id: number;
  context: { theme_label?: string; days_from_now?: number };
  created_at: string;
};

const ACTION_LABELS: Record<string, string> = {
  draft_stakeholder_update: "Draft Stakeholder Update",
  schedule_review: "Schedule Priority Review",
};

export default function ApprovalQueue() {
  const [actions, setActions] = useState<PendingAction[]>([]);
  const [loading, setLoading] = useState(true);
  const [processing, setProcessing] = useState<string | null>(null);
  const [lastResult, setLastResult] = useState<{ id: string; status: string; detail: string } | null>(null);

  const fetchPending = () => {
    fetch("http://localhost:8001/actions/pending")
      .then((res) => res.json())
      .then((data) => {
        setActions(data);
        setLoading(false);
      });
  };

  useEffect(() => {
    fetchPending();
  }, []);

  const handleDecision = async (actionId: string, decision: "approve" | "reject") => {
    setProcessing(actionId);
    const res = await fetch("http://localhost:8001/actions/" + actionId + "/" + decision, { method: "POST", headers: { "X-API-Key": "sIG08LTrOC5cW7vMExywja9Q1PlpVYU2" } });
    const data = await res.json();
    setLastResult({
      id: actionId,
      status: data.status,
      detail: decision === "approve" ? "Executed" : "Rejected - will not run",
    });
    setProcessing(null);
    fetchPending();
  };

  return (
    <div className="min-h-screen flex">
      <aside className="w-56 shrink-0 p-6 border-r" style={{ borderColor: "var(--line)" }}>
        <h2 className="font-display text-2xl mb-8" style={{ color: "var(--ink)" }}>Catalyst</h2>
        <nav className="flex flex-col gap-1">
          <a href="/" className="px-3 py-2 rounded-md text-sm" style={{ color: "var(--muted)" }}>
            Triage
          </a>
          <a className="px-3 py-2 rounded-md text-sm font-medium" style={{ background: "var(--ink)", color: "var(--paper)" }}>
            Approval Queue
          </a>
          <a className="px-3 py-2 rounded-md text-sm" style={{ color: "var(--muted)" }}>
            Activity Log
          </a>
        </nav>
      </aside>

      <main className="flex-1 p-12 max-w-3xl">
        <div className="mb-8">
          <span className="font-mono text-sm" style={{ color: "var(--muted)" }}>HUMAN-IN-THE-LOOP</span>
          <h1 className="font-display text-4xl mt-1" style={{ color: "var(--ink)" }}>Approval Queue</h1>
          <p className="text-sm mt-2" style={{ color: "var(--muted)" }}>
            These actions were generated by Catalyst but will not execute until you decide.
          </p>
        </div>

        {lastResult && (
          <div
            className="mb-6 px-4 py-3 rounded-md text-sm font-mono"
            style={{
              background: lastResult.status === "approved_and_executed" ? "var(--teal)" : "var(--brick)",
              color: "var(--paper)",
            }}
          >
            {lastResult.detail}
          </div>
        )}

        {loading && <p className="font-mono text-sm" style={{ color: "var(--muted)" }}>Loading queue...</p>}

        {!loading && actions.length === 0 && (
          <p className="font-mono text-sm" style={{ color: "var(--muted)" }}>Queue is empty. Nothing awaiting approval.</p>
        )}

        <div className="flex flex-col gap-4">
          {actions.map((action) => (
            <div
              key={action.action_id}
              className="p-6 rounded-lg border"
              style={{ borderColor: "var(--line)", background: "#FFFFFF" }}
            >
              <div className="flex items-start justify-between mb-3">
                <div>
                  <span className="font-mono text-xs px-2 py-0.5 rounded" style={{ background: "var(--paper)", color: "var(--ink)" }}>
                    {ACTION_LABELS[action.action_type] || action.action_type}
                  </span>
                  <h3 className="font-display text-xl mt-2" style={{ color: "var(--ink)" }}>
                    {action.context.theme_label}
                  </h3>
                </div>
                <span className="font-mono text-xs" style={{ color: "var(--muted)" }}>
                  Cluster {action.cluster_id}
                </span>
              </div>

              {action.context.days_from_now && (
                <p className="text-sm mb-4" style={{ color: "var(--muted)" }}>
                  Proposed date: {action.context.days_from_now} days from approval
                </p>
              )}

              <div className="flex gap-3 mt-4">
                <button
                  onClick={() => handleDecision(action.action_id, "approve")}
                  disabled={processing === action.action_id}
                  className="px-4 py-2 rounded-md text-sm font-medium disabled:opacity-50"
                  style={{ background: "var(--teal)", color: "var(--paper)" }}
                >
                  {processing === action.action_id ? "Working..." : "Approve & Execute"}
                </button>
                <button
                  onClick={() => handleDecision(action.action_id, "reject")}
                  disabled={processing === action.action_id}
                  className="px-4 py-2 rounded-md text-sm font-medium disabled:opacity-50 border"
                  style={{ borderColor: "var(--brick)", color: "var(--brick)" }}
                >
                  Reject
                </button>
              </div>
            </div>
          ))}
        </div>
      </main>
    </div>
  );
}
